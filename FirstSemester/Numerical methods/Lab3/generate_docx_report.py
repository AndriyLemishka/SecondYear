def fmt_float(val, decimals=15):
    return f"{val:.{decimals}f}".replace(".", ",")

def fmt_error(err):
    if err == 0.0:
        return "0,00000"
    elif abs(err - 100.0) < 1e-12:
        return "100"
    elif err >= 0.001:
        if err >= 10:
            return f"{err:.5f}".replace(".", ",")
        else:
            return f"{err:.8f}".rstrip("0").rstrip(".").replace(".", ",")
    else:
        exp = int(math.floor(math.log10(err)))
        mant = err / (10**exp)
        return f"{mant:.5f}E{exp:+03d}".replace(".", ",").replace("E+", "E").replace("E-0", "E-")

